import { Frame } from '../types/storyboard';

export interface FrameTiming {
  index: number;
  id: string;
  durationSec: number;
  startSec: number;
  endSec: number;
  startFrame24: number;
  endFrame24: number;
  frameCount24: number;
  timecodeIn: string;
  timecodeOut: string;
  sceneNumber: string;
  panelNumber: string;
  shotNumber: string;
  actionNotes: string;
  dialogueNotes: string;
  canvasData: string;
}

export interface AnimaticTimingData {
  timings: FrameTiming[];
  totalDurationSec: number;
  totalFrames24: number;
}

/**
 * Format seconds into standard SMPTE timecode (MM:SS:FF)
 */
export function formatTimecode(seconds: number, fps = 24): string {
  if (isNaN(seconds) || seconds < 0) seconds = 0;
  const totalFrames = Math.floor(seconds * fps);
  const ff = totalFrames % fps;
  const totalSeconds = Math.floor(totalFrames / fps);
  const ss = totalSeconds % 60;
  const mm = Math.floor(totalSeconds / 60) % 60;
  const hh = Math.floor(totalSeconds / 3600);

  const pad = (n: number, z = 2) => String(n).padStart(z, '0');
  if (hh > 0) {
    return `${pad(hh)}:${pad(mm)}:${pad(ss)}:${pad(ff)}`;
  }
  return `${pad(mm)}:${pad(ss)}:${pad(ff)}`;
}

/**
 * Human readable short time format (e.g. 0:04.5s or 1:12s)
 */
export function formatTimeShort(seconds: number): string {
  if (isNaN(seconds) || seconds < 0) seconds = 0;
  const mm = Math.floor(seconds / 60);
  const ss = (seconds % 60).toFixed(1);
  if (mm > 0) {
    return `${mm}m ${ss}s`;
  }
  return `${ss}s`;
}

/**
 * Calculate cumulative timings for all frames
 */
export function calculateAnimaticTimings(frames: Frame[], fps = 24): AnimaticTimingData {
  if (!frames || frames.length === 0) {
    return { timings: [], totalDurationSec: 0, totalFrames24: 0 };
  }

  let cumulativeSec = 0;
  let cumulativeFrames = 0;

  const timings: FrameTiming[] = frames.map((frame, index) => {
    const rawDuration = typeof frame.durationSec === 'number' && frame.durationSec > 0 
      ? frame.durationSec 
      : 1.0;
    // Snap to nearest frame at fps for precision
    const frameCount = Math.max(1, Math.round(rawDuration * fps));
    const normalizedDuration = frameCount / fps;

    const startSec = cumulativeSec;
    const endSec = cumulativeSec + normalizedDuration;
    const startFrame = cumulativeFrames;
    const endFrame = cumulativeFrames + frameCount;

    const timecodeIn = formatTimecode(startSec, fps);
    const timecodeOut = formatTimecode(endSec, fps);

    cumulativeSec = endSec;
    cumulativeFrames = endFrame;

    return {
      index,
      id: frame.id,
      durationSec: normalizedDuration,
      startSec,
      endSec,
      startFrame24: startFrame,
      endFrame24: endFrame,
      frameCount24: frameCount,
      timecodeIn,
      timecodeOut,
      sceneNumber: frame.sceneNumber || '1',
      panelNumber: frame.panelNumber || String(index + 1),
      shotNumber: frame.shotNumber || '1',
      actionNotes: frame.actionNotes || '',
      dialogueNotes: frame.dialogueNotes || '',
      canvasData: frame.canvasData || '',
    };
  });

  return {
    timings,
    totalDurationSec: cumulativeSec,
    totalFrames24: cumulativeFrames,
  };
}

/**
 * Find active frame index given current playhead time
 */
export function findFrameIndexAtTime(timings: FrameTiming[], timeSec: number): number {
  if (timings.length === 0) return 0;
  if (timeSec <= 0) return 0;
  const last = timings[timings.length - 1];
  if (timeSec >= last.endSec) return timings.length - 1;

  for (let i = 0; i < timings.length; i++) {
    if (timeSec >= timings[i].startSec && timeSec < timings[i].endSec) {
      return i;
    }
  }
  return timings.length - 1;
}

/**
 * Export Animatic Timing Sheet / Exposure Log as CSV
 */
export function exportAnimaticEdlCsv(projectTitle: string, frames: Frame[], fps = 24): void {
  const { timings, totalDurationSec, totalFrames24 } = calculateAnimaticTimings(frames, fps);

  const headers = [
    'Board #',
    'Scene',
    'Panel',
    'Shot',
    'Duration (Sec)',
    `Frames (@${fps}fps)`,
    'TC In',
    'TC Out',
    'Action / Camera Notes',
    'Dialogue / Audio Cue',
  ];

  const rows = timings.map((t) => [
    t.index + 1,
    `"${t.sceneNumber.replace(/"/g, '""')}"`,
    `"${t.panelNumber.replace(/"/g, '""')}"`,
    `"${t.shotNumber.replace(/"/g, '""')}"`,
    t.durationSec.toFixed(2),
    t.frameCount24,
    `"${t.timecodeIn}"`,
    `"${t.timecodeOut}"`,
    `"${t.actionNotes.replace(/"/g, '""')}"`,
    `"${t.dialogueNotes.replace(/"/g, '""')}"`,
  ]);

  // Summary Row
  rows.push([
    'TOTAL',
    '',
    `${frames.length} panels`,
    '',
    totalDurationSec.toFixed(2),
    totalFrames24,
    '00:00:00',
    formatTimecode(totalDurationSec, fps),
    `Project: ${projectTitle}`,
    'Generated by DrawDesk Animatic Engine',
  ]);

  const csvContent = [headers.join(','), ...rows.map((r) => r.join(','))].join('\r\n');
  const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  const safeTitle = (projectTitle || 'Storyboard').trim().replace(/[^a-z0-9_-]/gi, '_');
  link.download = `${safeTitle}_Animatic_Timing_Sheet.csv`;
  link.click();
  setTimeout(() => URL.revokeObjectURL(url), 2000);
}

export interface AnimaticRenderOptions {
  width?: number; // default 1920
  height?: number; // default 1080
  fps?: number; // default 24
  burnSubtitles?: boolean;
  burnTimecode?: boolean;
  showPegHoles?: boolean;
  theme?: 'dark' | 'light';
  scratchAudioUrl?: string | null;
}

/**
 * Preload all frame images into HTMLImageElements for instantaneous video rendering
 */
function preloadFrameImages(frames: Frame[]): Promise<HTMLImageElement[]> {
  return Promise.all(
    frames.map((frame) => {
      return new Promise<HTMLImageElement>((resolve) => {
        const img = new Image();
        img.onload = () => resolve(img);
        img.onerror = () => resolve(img);
        img.src = frame.canvasData || '';
      });
    })
  );
}

/**
 * Render the entire animatic sequence into a downloadable .webm video following exact frame timings
 */
export async function renderAnimaticVideo(
  projectTitle: string,
  frames: Frame[],
  options: AnimaticRenderOptions = {},
  onProgress?: (progressPct: number, statusText: string) => void
): Promise<Blob> {
  const width = options.width || 1280;
  const height = options.height || 720;
  const fps = options.fps || 24;
  const burnSubtitles = options.burnSubtitles ?? true;
  const burnTimecode = options.burnTimecode ?? true;
  const showPegHoles = options.showPegHoles ?? true;
  const isDark = options.theme === 'dark';

  const { timings, totalDurationSec } = calculateAnimaticTimings(frames, fps);

  onProgress?.(5, 'Preloading storyboard artwork...');
  const images = await preloadFrameImages(frames);

  // Setup offscreen canvas
  const canvas = document.createElement('canvas');
  canvas.width = width;
  canvas.height = height;
  const ctx = canvas.getContext('2d', { alpha: false });
  if (!ctx) throw new Error('Could not initialize 2D canvas context');

  // Video recording setup
  const stream = canvas.captureStream(fps);

  let audioCtx: AudioContext | null = null;
  let audioSource: AudioNode | null = null;
  let audioDestination: MediaStreamAudioDestinationNode | null = null;
  let audioElement: HTMLAudioElement | null = null;

  // If user provided a scratch audio track, mix it into the video stream
  if (options.scratchAudioUrl) {
    try {
      audioElement = new Audio(options.scratchAudioUrl);
      audioElement.currentTime = 0;
      audioCtx = new AudioContext();
      audioSource = audioCtx.createMediaElementSource(audioElement);
      audioDestination = audioCtx.createMediaStreamDestination();
      audioSource.connect(audioDestination);
      audioSource.connect(audioCtx.destination);
      const audioTrack = audioDestination.stream.getAudioTracks()[0];
      if (audioTrack) {
        stream.addTrack(audioTrack);
      }
    } catch (e) {
      console.warn('Scratch audio attachment fallback:', e);
    }
  }

  // Pick supported mimeType
  const mimeTypes = [
    'video/webm;codecs=vp9',
    'video/webm;codecs=vp8',
    'video/webm',
    'video/mp4',
  ];
  let chosenMime = 'video/webm';
  for (const mime of mimeTypes) {
    if (MediaRecorder.isTypeSupported(mime)) {
      chosenMime = mime;
      break;
    }
  }

  const recordedChunks: Blob[] = [];
  const recorder = new MediaRecorder(stream, {
    mimeType: chosenMime,
    videoBitsPerSecond: 4500000,
  });

  recorder.ondataavailable = (e) => {
    if (e.data && e.data.size > 0) {
      recordedChunks.push(e.data);
    }
  };

  const drawFrame = (frameIndex: number, currentSec: number) => {
    const timing = timings[frameIndex] || timings[0];
    const img = images[frameIndex];

    // 1. Background
    ctx.fillStyle = isDark ? '#141418' : '#FAF8F5';
    ctx.fillRect(0, 0, width, height);

    // 2. Simulated Acme Peg Bar at top (traditional animation desk aesthetic)
    if (showPegHoles) {
      const pegBarHeight = Math.round(height * 0.045);
      ctx.fillStyle = isDark ? '#1f1f26' : '#EDE8DF';
      ctx.fillRect(0, 0, width, pegBarHeight);
      ctx.strokeStyle = isDark ? '#2e2e38' : '#D8D2C6';
      ctx.lineWidth = 1;
      ctx.strokeRect(0, 0, width, pegBarHeight);

      // Acme peg holes (left rectangle, center round pin, right rectangle)
      const cx = width / 2;
      const py = pegBarHeight / 2;
      ctx.fillStyle = isDark ? '#0d0d10' : '#454038';

      // Left acme peg slot
      ctx.fillRect(cx - 140, py - 3, 22, 6);
      // Center round peg hole
      ctx.beginPath();
      ctx.arc(cx, py, 4, 0, Math.PI * 2);
      ctx.fill();
      // Right acme peg slot
      ctx.fillRect(cx + 118, py - 3, 22, 6);

      // LIIME / Acme watermark in peg bar
      ctx.fillStyle = isDark ? '#52525e' : '#8c857b';
      ctx.font = 'bold 9px monospace';
      ctx.textAlign = 'left';
      ctx.fillText('ACME 12-FIELD REGISTRATION • ANIMATIC', 16, py + 3);
    }

    // 3. Storyboard Artwork (Centered 16:9 projection)
    const pegOffset = showPegHoles ? height * 0.045 : 0;
    const availableH = height - pegOffset - (burnSubtitles ? 80 : 0);
    const aspect = 16 / 9;

    let drawW = width * 0.94;
    let drawH = drawW / aspect;
    if (drawH > availableH * 0.94) {
      drawH = availableH * 0.94;
      drawW = drawH * aspect;
    }

    const drawX = (width - drawW) / 2;
    const drawY = pegOffset + (availableH - drawH) / 2;

    // Subtle paper backing card
    ctx.fillStyle = isDark ? '#1c1c22' : '#FFFFFF';
    ctx.shadowColor = 'rgba(0, 0, 0, 0.25)';
    ctx.shadowBlur = 12;
    ctx.shadowOffsetY = 4;
    ctx.fillRect(drawX, drawY, drawW, drawH);
    ctx.shadowColor = 'transparent';

    ctx.strokeStyle = isDark ? '#32323e' : '#D3CFC6';
    ctx.lineWidth = 1.5;
    ctx.strokeRect(drawX, drawY, drawW, drawH);

    // Draw artwork
    if (img && img.naturalWidth > 0) {
      ctx.drawImage(img, drawX, drawY, drawW, drawH);
    }

    // 4. Timecode & HUD Burn-in (Top corners)
    if (burnTimecode) {
      const topHudY = (showPegHoles ? height * 0.045 : 0) + 24;

      // Left: Scene & Panel
      ctx.fillStyle = 'rgba(0, 0, 0, 0.65)';
      ctx.fillRect(16, topHudY - 14, 180, 24);
      ctx.fillStyle = '#ffffff';
      ctx.font = 'bold 11px monospace';
      ctx.textAlign = 'left';
      ctx.fillText(`SCENE ${timing.sceneNumber} • PANEL ${timing.panelNumber}`, 24, topHudY + 2);

      // Right: Timecode & Board Counter
      const tcStr = `${formatTimecode(currentSec, fps)} | BOARD ${frameIndex + 1}/${timings.length}`;
      ctx.fillStyle = 'rgba(0, 0, 0, 0.65)';
      ctx.fillRect(width - 240, topHudY - 14, 224, 24);
      ctx.fillStyle = '#38bdf8';
      ctx.font = 'bold 11px monospace';
      ctx.textAlign = 'right';
      ctx.fillText(tcStr, width - 24, topHudY + 2);
    }

    // 5. Subtitle & Dialogue Burn-in (Lower thirds)
    if (burnSubtitles && (timing.dialogueNotes || timing.actionNotes)) {
      const subH = 74;
      const subY = height - subH;
      ctx.fillStyle = 'rgba(12, 12, 16, 0.88)';
      ctx.fillRect(0, subY, width, subH);
      ctx.fillStyle = '#38bdf8';
      ctx.fillRect(0, subY, width, 2);

      if (timing.dialogueNotes) {
        ctx.fillStyle = '#fef08a'; // Classic film yellow subtitle
        ctx.font = '600 15px system-ui, -apple-system, sans-serif';
        ctx.textAlign = 'center';
        ctx.fillText(`“${timing.dialogueNotes}”`, width / 2, subY + 28);
      }

      if (timing.actionNotes) {
        ctx.fillStyle = '#94a3b8';
        ctx.font = 'italic 12px system-ui, -apple-system, sans-serif';
        ctx.textAlign = 'center';
        ctx.fillText(timing.actionNotes, width / 2, subY + (timing.dialogueNotes ? 52 : 40));
      }
    }
  };

  return new Promise((resolve, reject) => {
    recorder.onstop = () => {
      try {
        if (audioElement) {
          audioElement.pause();
        }
        if (audioCtx) {
          audioCtx.close().catch(() => {});
        }
      } catch {}
      const blob = new Blob(recordedChunks, { type: chosenMime });
      resolve(blob);
    };

    recorder.onerror = (err) => {
      reject(err);
    };

    recorder.start(100);

    if (audioElement) {
      audioElement.play().catch(() => {});
    }

    // Step through each timing segment sequentially
    let currentTimingIdx = 0;
    const intervalMs = 1000 / fps;
    const totalTicks = Math.round(totalDurationSec * fps);
    let currentTick = 0;

    const tick = () => {
      if (currentTick >= totalTicks) {
        // Draw last frame once more and finalize
        drawFrame(timings.length - 1, totalDurationSec);
        setTimeout(() => {
          if (recorder.state === 'recording') {
            recorder.stop();
          }
        }, 300);
        return;
      }

      const currentSec = currentTick / fps;
      currentTimingIdx = findFrameIndexAtTime(timings, currentSec);
      drawFrame(currentTimingIdx, currentSec);

      if (currentTick % fps === 0 || currentTick === totalTicks - 1) {
        const pct = Math.min(99, Math.round((currentTick / totalTicks) * 100));
        onProgress?.(
          pct,
          `Rendering animatic board ${currentTimingIdx + 1} of ${timings.length} (${formatTimeShort(currentSec)} / ${formatTimeShort(totalDurationSec)})...`
        );
      }

      currentTick++;
      setTimeout(tick, intervalMs);
    };

    // Kick off animation ticks
    drawFrame(0, 0);
    setTimeout(tick, intervalMs);
  });
}
